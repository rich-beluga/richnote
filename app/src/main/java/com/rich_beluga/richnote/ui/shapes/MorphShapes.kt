package com.rich_beluga.richnote.ui.shapes

import androidx.core.graphics.PathParser
import androidx.graphics.shapes.RoundedPolygon

fun roundedPolygonFromSvgPath(
    pathData: String,
    acceptableError: Float = 0.05f
): RoundedPolygon {
    val androidPath = PathParser.createPathFromPathData(pathData)
    val approx = androidPath.approximate(acceptableError)

    val points = ArrayList<Float>(approx.size)
    for (i in approx.indices step 3) {
        points.add(approx[i + 1]) // x
        points.add(approx[i + 2]) // y
    }

    if (points.size >= 4) {
        val firstX = points[0]
        val firstY = points[1]
        val lastX = points[points.size - 2]
        val lastY = points[points.size - 1]
        val dx = firstX - lastX
        val dy = firstY - lastY
        if (dx * dx + dy * dy < 1e-3f) {
            points.removeAt(points.size - 1)
            points.removeAt(points.size - 1)
        }
    }

    return RoundedPolygon(vertices = normalizeVertices(points.toFloatArray()))
}

private fun normalizeVertices(vertices: FloatArray): FloatArray {
    if (vertices.isEmpty()) return vertices

    var minX = Float.MAX_VALUE
    var maxX = -Float.MAX_VALUE
    var minY = Float.MAX_VALUE
    var maxY = -Float.MAX_VALUE

    for (i in vertices.indices step 2) {
        val x = vertices[i]
        val y = vertices[i + 1]
        if (x < minX) minX = x
        if (x > maxX) maxX = x
        if (y < minY) minY = y
        if (y > maxY) maxY = y
    }

    val centerX = (minX + maxX) / 2f
    val centerY = (minY + maxY) / 2f
    val maxDimension = maxOf(maxX - minX, maxY - minY) / 2f

    if (maxDimension == 0f) return vertices

    val result = FloatArray(vertices.size)
    for (i in vertices.indices step 2) {
        result[i] = (vertices[i] - centerX) / maxDimension
        result[i + 1] = (vertices[i + 1] - centerY) / maxDimension
    }
    return result
}

